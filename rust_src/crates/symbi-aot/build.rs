// a kernel instance's discretization config — the three facts that travel together per
// instance (docs/design/18): the coordinate system, the vector-component count `ncomp`
// (the momentum/velocity DOF), and the grid-axis -> coordinate-role map `axes`. cartesian
// and spherical use the identity axes + ncomp = ndim (the grid axes ARE the coordinates);
// cylindrical r-z AXISYMMETRIC decouples them — a 2-axis (r,z) grid carrying a 3-component
// velocity (v_r, v_phi, v_z), phi folded as a symmetry coordinate that carries the swirl.
#[derive(Clone)]
struct Geom {
    coords:  Coords,
    ncomp:   u8,
    axes:    Vec<usize>,
    // per-grid-axis spacing (len == naxes == ndim). defaults to all-uniform;
    // override with `with_spacing` for the log-radial spherical instances.
    spacing: Vec<Spacing>,
}

impl Geom {
    // the common shape: identity-or-decoupled axes with all-uniform spacing.
    fn make(coords: Coords, ncomp: u8, axes: Vec<usize>) -> Self {
        let spacing = vec![Spacing::Uniform; axes.len()];
        Self { coords, ncomp, axes, spacing }
    }
    fn cart(ndim: u8) -> Self {
        Self::make(Coords::Cartesian, ndim, (0..ndim as usize).collect())
    }
    fn sph(ndim: u8) -> Self {
        Self::make(Coords::Spherical, ndim, (0..ndim as usize).collect())
    }
    // identity-axis instance at an arbitrary coordinate system (ncomp == ndim, the
    // grid axes ARE the coordinates) — the body-source / geometry-probe shape.
    fn identity(coords: Coords, ndim: u8) -> Self {
        Self::make(coords, ndim, (0..ndim as usize).collect())
    }
    // cylindrical r-z axisymmetric: 2-axis grid (r,z) -> coords [0,2], 3-component velocity
    // (the swirl v_phi is carried as the out-of-plane DOF). ncomp > naxes -> "_cyl_rz".
    fn cyl_rz() -> Self {
        Self::make(Coords::Cylindrical, 3, vec![0, 2])
    }
    // cylindrical r-phi disk: 2-axis grid (r,phi) -> coords [0,1], 2-component velocity
    // (the natural cylindrical 2D plane). ncomp == naxes -> "_cyl".
    fn cyl_rphi() -> Self {
        Self::make(Coords::Cylindrical, 2, vec![0, 1])
    }
    // cylindrical r-phi DISK MHD: 2-axis grid (r,phi) -> coords [0,1], 3-component B/velocity
    // (the out-of-plane vertical B_z / v_z is the lifted DOF). ncomp > naxes BUT axes=[0,1]
    // -> "_cyl_rphi" (distinct from r-z [0,2]; both are DOF=3 so the suffix keys on the axes).
    fn cyl_rphi_mhd() -> Self {
        Self::make(Coords::Cylindrical, 3, vec![0, 1])
    }
    // cylindrical 1D radial: r only (coords [0]), 1-component velocity. the radial
    // hoop-pressure source + area ~ r divergence. ncomp == naxes -> "_cyl".
    fn cyl_1d() -> Self {
        Self::make(Coords::Cylindrical, 1, vec![0])
    }
    // cylindrical 3D (r,phi,z): full natural plane, coords [0,1,2], 3-component velocity.
    // ncomp == naxes -> "_cyl" (NDIM=3 disambiguates from the 2D _cyl in the name).
    fn cyl_3d() -> Self {
        Self::make(Coords::Cylindrical, 3, vec![0, 1, 2])
    }
    // override the default all-uniform spacing (e.g. a log-radial spherical grid).
    fn with_spacing(mut self, spacing: Vec<Spacing>) -> Self {
        self.spacing = spacing;
        self
    }
    // the cylindrical 2D plane is keyed on the AXIS SET (matching the runtime mhd_geom_suffix):
    // r-z axisymmetric [0,2] -> "_cyl_rz" (out-of-plane phi); r-phi disk MHD [0,1] with the DOF
    // lift (ncomp>naxes) -> "_cyl_rphi" (out-of-plane z). the natural hydro disk [0,1] DOF==naxes
    // and 1D/3D stay "_cyl" (DOF==ndim, matching the hydro geom_suffix). both 2D MHD planes are
    // DOF=3, so ncomp-vs-naxes alone can't tell them apart — the axes do.
    fn suffix(&self) -> &'static str {
        match self.coords {
            Coords::Cartesian => "",
            Coords::Spherical => "_sph",
            Coords::Cylindrical => match self.axes.as_slice() {
                [0, 2] => "_cyl_rz",
                [0, 1] if self.ncomp as usize > self.axes.len() => "_cyl_rphi",
                _ => "_cyl",
            },
        }
    }
}

// every gen_* emits a GV-traced kernel through `emit_gv` — Gv is the sole IR front end; the
// legacy DiscretizeCtx / Expr DSL path is gone.

// the emit chokepoint for a GV-TRACED kernel (symbi-hydro physics instantiated at S=Gv): the
// `GvKernel` already carries the graph + the ABI manifest (field inputs, scalar params, coord
// axes), so the gen just asserts the graph is clean and write_both's it with the recorded
// manifest.
fn emit_gv(out_dir: &str, kernel_name: &str, ndim: u8, k: &GvKernel, writes: &[(String, FieldBind, NodeId)]) {
    assert!(!k.graph.has_errors(), "{kernel_name} (gv) graph errors: {:?}", k.graph.errors());
    // docs/design/22 Gate 3: the smem tile intent (per-axis SLAB declared by the
    // builder via with_tile_spec) is OPT-IN behind SYMBI_GPU_SMEM, so the default
    // build stays byte-identical (flat) until the GPU smem path is hardware-validated.
    // the `rerun-if-env-changed` in `main` keeps the A/B honest — without it cargo
    // would silently reuse a cached build and invalidate a smem-on-vs-off comparison.
    let tile_spec = if std::env::var_os("SYMBI_GPU_SMEM").is_some() {
        k.infer_tile_spec()
    } else {
        None
    };
    write_both(out_dir, &k.graph, &KernelEmitInputs {
        kernel_name,
        ndim,
        target:           TargetConfig { target: Target::Cuda, precision: Precision::F64 },
        field_inputs:     &k.field_inputs,
        scalar_params:    &k.scalar_params,
        field_writes:     writes,
        coord_components: &k.coord_components,
        device_preamble:  &[],
        tile_spec: tile_spec.as_ref(),
    });
}

// the curvilinear geometric momentum source the godunov binds, by regime prefix: RMHD's
// magnetic-tension-aware source via prim+bcell, else the hydro pressure+inertial source
// via cons.mom (no-op for Cartesian).
fn geo_source(prefix: &str) -> GeoSource {
    match prefix {
        "rmhd" => GeoSource::Rmhd,
        "nmhd" => GeoSource::NewtonianMhd,
        "imhd" => GeoSource::IsothermalMhd,
        _ => GeoSource::Hydro { inertial: matches!(prefix, "iso" | "adiabatic" | "srhd") },
    }
}

// the SINGLE godunov emit chokepoint for BOTH fused / unfused variants. the
// integrator stage is no longer a codegen axis: one `{prefix}_godunov_stage{geom_suffix}_{D}d`
// kernel takes the SSP Shu-Osher convex coefficients `(a0, ac)` as RUNTIME scalars, so the
// same kernel serves forward-Euler, SSP-RK2, and SSP-RK3 (the driver feeds the per-stage
// coefficients). `fused = None` emits the plain kernel; `fused = Some((slug, specs))` adds
// the `_with_{slug}` infix and splices the specs into the forward-Euler operator. one helper
// covers the cross-product — (fused × regime × ndim × geometry) is data, never copy-paste.
fn gen_godunov_stage(
    out_dir: &str,
    ndim: u8,
    prefix: &str,
    has_energy: bool,
    geom: Geom,
    fused: Option<(&str, &[&symbi_hydro::source_spec::SourceSpec])>,
) {
    let suffix_with = fused.map(|(slug, _)| format!("_with_{slug}")).unwrap_or_default();
    let name = format!("{prefix}_godunov_stage{suffix_with}{}_{ndim}d", geom.suffix());
    let no_sources: [&symbi_hydro::source_spec::SourceSpec; 0] = [];
    let sources: &[&symbi_hydro::source_spec::SourceSpec] = match fused {
        Some((_, s)) => s,
        None         => &no_sources,
    };
    let (k, writes) = symbi_discretize::gv::godunov_stage_gv_with_fused_sources(
        geom.coords, &geom.spacing, &geom.axes, ndim, geom.ncomp as usize, has_energy,
        geo_source(prefix), sources, /* mag_from_bcell = */ false, // unfused: geo source reads prim.mag
    );
    emit_gv(out_dir, &name, ndim, &k, &writes);
}

// the IMMERSED-BODY source fused into the godunov stage (frame-correct: Cartesian
// physics projected onto the physical basis). its own bake — the body source is a
// set of coord-dependent `BuiltSource`s (`body_source_built`), not a coord-agnostic
// `SourceSpec` family, so it doesn't ride the FUSED_FAMILIES loop. one launch:
// `cons_new = godunov(cons) + ac*dt*(gravity + accretion)` for MAX_BODIES bodies.
fn gen_godunov_with_body_source(out_dir: &str, ndim: u8, prefix: &str, has_energy: bool, geom: Geom) {
    let name = format!("{prefix}_godunov_stage_with_body_source{}_{ndim}d", geom.suffix());
    let built = symbi_discretize::body_source_built(
        geom.coords, ndim as usize, geom.ncomp as usize, &geom.axes, MAX_BODIES, has_energy,
    );
    let refs: Vec<(&str, &symbi_hydro::source_spec::BuiltSource)> =
        built.iter().map(|(t, b)| (t.as_str(), b)).collect();
    let (k, writes) = symbi_discretize::gv::godunov_stage_gv_with_fused_built(
        geom.coords, &geom.spacing, &geom.axes, ndim, geom.ncomp as usize, has_energy,
        geo_source(prefix), &refs, /* mag_from_bcell = */ false,
    );
    emit_gv(out_dir, &name, ndim, &k, &writes);
}

// the STANDALONE ADDITIVE source kernel `{prefix}_source_with_{slug}{geom}_{D}d`: `cons += dt*S`
// for the spec family, as a separate per-stage pass (the general source executor). same splice as
