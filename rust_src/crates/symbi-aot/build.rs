// P3.3: the isothermal face FLUX — reconstruction composed with the one
// canonical HLLE (symbi_discretize::iso_hlle_flux). dimension-generic: it loops
// the momentum components internally; codegen instantiates one kernel per (ndim,
// sweep dir) — the reconstruction axis `dir` is baked into the kernel instance.
fn gen_iso_face_flux(out_dir: &str, ndim: u8, dir: u8) {
    let name = format!("iso_face_flux_{ndim}d_{dir}");
    // the gv single-source physics: PLM reconstruction (Gv stencil) composed with
    // symbi-hydro's `riemann::hlle` at the `IsoNewtonian` regime — the PURE iso (constant
    // cs, p=cs^2*rho recomputed from rho, NO reconstructed prim.pre, no energy flux),
    // replacing the `iso_hlle_flux` Expr builder. cartesian-only + ncomp == ndim.
    let (k, writes) = match ndim {
        1 => symbi_discretize::gv::iso_flux_gv::<1>(dir),
        2 => symbi_discretize::gv::iso_flux_gv::<2>(dir),
        3 => symbi_discretize::gv::iso_flux_gv::<3>(dir),
        _ => panic!("iso_flux_gv: unsupported ndim {ndim}"),
    };
    emit_gv(out_dir, &name, ndim, &k, &writes);
}

// the adiabatic face flux: hlle_flux with the energy component (mass + momentum +
// energy). same EOS-generic body as the iso flux, plus E = p/(gamma-1)+0.5*rho|v|^2
// and F_E = (E+p)*vn.
fn gen_adiabatic_face_flux(out_dir: &str, ndim: u8, dir: u8, geom: Geom) {
    let name = format!("adiabatic_face_flux{}_{ndim}d_{dir}", geom.suffix());
    // the CARTESIAN adiabatic face flux is the gv single-source physics: PLM reconstruction
    // (a Gv stencil via field_shifted) composed with symbi-hydro's `riemann::hlle` at S=Gv
    // (adiabatic_flux_gv) — replacing the hand-written hlle_flux Expr builder + its
    // per-component U/F. ncomp == ndim == D, sweep coordinate == grid axis `dir`. cyl r-z
    // (ncomp != ndim, non-identity axes) stays on the Expr builder below until the gv flux
    // generalizes over ncomp + the axes mapping (the c2p pattern). numerically equiv (ULP).
    let (k, writes) = if geom.coords == Coords::Cartesian {
        match ndim {
            1 => symbi_discretize::gv::adiabatic_flux_gv::<1>(dir),
            2 => symbi_discretize::gv::adiabatic_flux_gv::<2>(dir),
            3 => symbi_discretize::gv::adiabatic_flux_gv::<3>(dir),
            _ => panic!("adiabatic_flux_gv: unsupported ndim {ndim}"),
        }
    } else {
        // cyl r-z (ncomp=3 swirl on the 2D (r,z) grid): the sweep coordinate is axes[dir].
        assert!(geom.ncomp == 3 && ndim == 2, "non-cartesian adiabatic flux is only cyl r-z");
        symbi_discretize::gv::adiabatic_flux_cyl_rz_gv(dir)
    };
    emit_gv(out_dir, &name, ndim, &k, &writes);
}

