fn main() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    gen_godunov_mass_1d(&out_dir);
    // amr field transfer (docs/design/22 phase 2): the refinement-lattice
    // pullbacks at ratio 2, every dimension.
    for ndim in 1u8..=3 {
        gen_refine_transfer(&out_dir, ndim);
    }
    gen_scalar_ghost_fill(&out_dir);
    // geometry-algebra probes: cartesian + spherical, uniform + log radial spacing.
    gen_geometry_probe(&out_dir, 1, Coords::Cartesian, &[Spacing::Uniform], "geom_cart_unif_1d");
    gen_geometry_probe(&out_dir, 1, Coords::Spherical, &[Spacing::Uniform], "geom_sph_unif_1d");
    gen_geometry_probe(&out_dir, 1, Coords::Spherical, &[Spacing::Log], "geom_sph_log_1d");
    gen_geometry_probe(
        &out_dir, 2, Coords::Spherical, &[Spacing::Log, Spacing::Uniform], "geom_sph_log_2d",
    );
    // P2: the spherical area-weighted mass-law divergence probe.
    gen_godunov_mass_sph_1d(&out_dir);
    // P3/P3b: the SPHERICAL adiabatic hydro kernels (the curvilinear instances the
    // M-generic AdiabaticSubstrateKernelSet selects on a spherical SimState) — the SAME
    // builders as Cartesian with set_geometry(Spherical): area-weighted divergence +
    // geometric pressure source (+ inertial for ndim>=2) + per-cell CFL widths. the
    // adiabatic CFL shares the iso wave-speed map.
    for ndim in 1u8..=3 {
        gen_curvilinear_hydro(&out_dir, ndim, Geom::sph(ndim));
    }
    // P3b (RMHD): the full relativistic-MHD geometric source (3D spherical) — pressure +
    // gas inertial + magnetic tension, via the RMHD adapter onto the generic builder.
    gen_rmhd_geometric_source(&out_dir, Geom::sph(3));
    gen_rmhd_geometric_source(&out_dir, Geom::cyl_3d());
    // P4: the iso CFL wave-speed map with per-cell physical widths (log-spherical).
    gen_iso_wave_speed_map_sph_log_1d(&out_dir);
    // P3b: the Newtonian inertial (centrifugal/coriolis) momentum source probe.
    gen_inertial_momentum_probe_sph_2d(&out_dir);
    // the three hydro regimes are FULLY D-GENERIC: one builder each, instantiated
    // at every dimension 1..=3 (and per sweep dir for the flux — the reconstruction
    // axis is baked per kernel instance). the D-generic SubstrateKernelSet<.., const D>
    // picks the instance by name (`kernel_by_name`). the godunov / snapshot / rk2
    // builders are EOS-generic — `has_energy` adds the energy conservation law
    // (iso = false; adiabatic + srhd = true).
    for ndim in 1u8..=3 {
        // isothermal Euler (no energy law; the EOS closure p = cs^2*rho is in c2p).
        gen_iso_c2p(&out_dir, ndim);
        gen_iso_wave_speed_map(&out_dir, ndim, Geom::cart(ndim));
        gen_iso_ghost_fill(&out_dir, ndim, Geom::cart(ndim));
        gen_godunov_stage(&out_dir, ndim, "iso", false, Geom::cart(ndim), None);
        gen_snapshot(&out_dir, ndim, "iso", false, Geom::cart(ndim));
        // adiabatic (ideal-gas Euler): the same EOS-generic update + the energy law
        // and the closed-form c2p closure (shares iso's wave-speed map + ghost fill).
        gen_adiabatic_c2p(&out_dir, ndim, Geom::cart(ndim));
        gen_godunov_stage(&out_dir, ndim, "adiabatic", true, Geom::cart(ndim), None);
        gen_snapshot(&out_dir, ndim, "adiabatic", true, Geom::cart(ndim));
        // SRHD (special-relativistic Euler): the ITERATIVE c2p (20-step masked
        // Newton, docs/design/14) + the relativistic flux/wave-speed map; the
        // godunov/snapshot are the SAME EOS-generic builders (D/S_k/tau).
        gen_srhd_c2p(&out_dir, ndim, 20);
        gen_srhd_wave_speed_map(&out_dir, ndim, Geom::cart(ndim));
        gen_godunov_stage(&out_dir, ndim, "srhd", true, Geom::cart(ndim), None);
        gen_snapshot(&out_dir, ndim, "srhd", true, Geom::cart(ndim));
        // one face flux per sweep dir (the reconstruction axis is baked).
        for dir in 0..ndim {
            gen_iso_face_flux(&out_dir, ndim, dir);
            gen_adiabatic_face_flux(&out_dir, ndim, dir, Geom::cart(ndim));
            gen_srhd_face_flux(&out_dir, ndim, dir);
            // HLLC variants — contact-resolving 3-wave solver, available on every
            // regime that has a contact wave. iso is HLLE-only by physics. cartesian
            // only for now (curvilinear HLLC = follow-up).
            gen_adiabatic_hllc_face_flux(&out_dir, ndim, dir);
            gen_srhd_hllc_face_flux(&out_dir, ndim, dir);
        }
    }
    // RMHD HLLC + HLLD — 1D + 3D variants matching the HLLE RMHD layout
    // (no 2D RMHD today). HLLD is now fully carrier-generic (see hlld.rs).
    gen_rmhd_hllc_face_flux(&out_dir, 1, 0);
    gen_rmhd_hlld_face_flux(&out_dir, 1, 0);
    for dir in 0..3u8 {
        gen_rmhd_hllc_face_flux(&out_dir, 3, dir);
        gen_rmhd_hlld_face_flux(&out_dir, 3, dir);
    }
    // **B6-iv (Phase 3 + 3b + 4c-restructure + vi) — the DRY AOT-bake matrix**.
    //
    // every fused godunov kernel symbi-aot emits is one point in the cube:
    //
    //   {regime}  ×  {fused family}  ×  {ndim}  ×  {integrator kind}  ×  {geometry}
    //
    // declaring it as data + a nested loop replaces the copy-paste fan-out.
    // adding SRHD / RMHD = one row in `REGIMES`; adding accretion = one row
    // in `FAMILIES`; adding spherical = wrap a `for geom in GEOMS` loop
    // (deferred until the curvilinear fused path validates on GPU). this
    // is the LOAD-BEARING shape: every new fused-kernel variant is a data
    // addition, never a new emit block. ONE godunov-stage kernel per cell
    // serves every SSP scheme — the integrator stage is a runtime coefficient,
    // no longer a codegen axis.
    for ndim in 1u8..=3 {
        for regime in REGIMES {
            for family in FUSED_FAMILIES {
                let specs = family.source_specs(ndim as usize, regime.has_energy);
                let refs: Vec<&symbi_hydro::source_spec::SourceSpec> = specs.iter().collect();
                // the FUSED variant — source folded into the godunov stage (one launch).
                gen_godunov_stage(
                    &out_dir, ndim, regime.prefix, regime.has_energy,
                    Geom::cart(ndim), Some((family.slug(), &refs)),
                );
                // the STANDALONE ADDITIVE variant — `cons += dt*S` as a separate per-stage pass.
                // the general source executor + the proven-equivalent decomposition of the fused
                // stage (plain godunov + this pass == fused stage; the S2 equivalence test).
                gen_source_apply(
                    &out_dir, ndim, regime.prefix, regime.has_energy,
                    Geom::cart(ndim), family.slug(), &refs,
                );
            }
            // the immersed-body source, fused (Cartesian for now; cyl/sph below).
            gen_godunov_with_body_source(
                &out_dir, ndim, regime.prefix, regime.has_energy, Geom::cart(ndim),
            );
        }
    }
    // the CYLINDRICAL r-z AXISYMMETRIC adiabatic family (docs/design/18): a 2-axis
    // (r, z) grid carrying a 3-component velocity — v_phi is the swirl on the folded
    // phi symmetry coordinate. ncomp=3, axes=[0,2], Cylindrical. the SAME EOS-generic
    // builders as the cartesian set, only the Geom differs (the inertial centrifugal
    // source + area-weighted divergence + phi-momentum advection fall out of it). the
    // `_cyl_rz` suffix (ncomp>naxes) matches the runtime geom_suffix; full kernel family
    // because DOF=3 != ndim=2 (the c2p/flux/snapshot/ghost can't reuse the cartesian ncomp).
    let cyl = Geom::cyl_rz();
    gen_adiabatic_c2p(&out_dir, 2, cyl.clone());
    gen_iso_wave_speed_map(&out_dir, 2, cyl.clone());
    gen_iso_ghost_fill(&out_dir, 2, cyl.clone());
    gen_godunov_stage(&out_dir, 2, "adiabatic", true, cyl.clone(), None);
    gen_snapshot(&out_dir, 2, "adiabatic", true, cyl.clone());
    for dir in 0..2 {
        gen_adiabatic_face_flux(&out_dir, 2, dir, cyl.clone());
    }
    // the CYLINDRICAL NATURAL (DOF == NDIM) hydro family for ALL THREE regimes (iso /
    // adiabatic / srhd), at 1D (radial), 2D (r-phi disk plane), and 3D (r,phi,z) — the
    // SAME gen_curvilinear_hydro helper that drives the spherical cells. only the
    // geometry-dependent godunov + wave-speed are "_cyl" (area-weighted divergence +
    // centrifugal/coriolis/hoop source); the c2p/flux/snapshot/ghost reuse the cartesian
    // ncomp == NDIM instances (DOF==D -> "" suffix). r-phi (2D) is the disk-evolve hydro
    // the immersed bodies ride (docs/design/19/20). the r-z AXISYMMETRIC swirl (DOF=3,
    // above) is the separate DOF-lifted family (newton only).
    gen_curvilinear_hydro(&out_dir, 1, Geom::cyl_1d());
    gen_curvilinear_hydro(&out_dir, 2, Geom::cyl_rphi());
    gen_curvilinear_hydro(&out_dir, 3, Geom::cyl_3d());
    // immersed-body forward source (gravity + accretion, docs/design/19 P1/P2/P4): the cons->cons
    // kernel, emitted per grid dimension (regime-agnostic) + the curvilinear variants (generic
    // physical-basis gravity, docs/design/19 P4). cylindrical 2D = the r-phi disk plane (natural
    // axes). 3D / spherical body emission follow once the generic transforms are wired (the
    // builder already handles them).
    for ndim in 1u8..=3 {
        gen_body_source(&out_dir, ndim, Coords::Cartesian);
    }
    // curvilinear body source (one generic builder per geometry): cyl r-phi disk plane (2D) +
    // r-phi-z (3D); spherical meridional (2D) + full (3D). the r-z axisymmetric body shares the
    // cyl 2D name with r-phi and needs a runtime axis-role to disambiguate (deferred).
    gen_body_source(&out_dir, 2, Coords::Cylindrical);
    gen_body_source(&out_dir, 3, Coords::Cylindrical);
    gen_body_source(&out_dir, 2, Coords::Spherical);
    gen_body_source(&out_dir, 3, Coords::Spherical);
    // backward feedback (force[ndim] + 3D torque + mass), per geometry, ndim >= 2.
    for &cc in &[Coords::Cartesian, Coords::Cylindrical, Coords::Spherical] {
        gen_body_feedback(&out_dir, 2, cc);
        gen_body_feedback(&out_dir, 3, cc);
    }
    // isothermal body source/feedback (no energy slot; cs from prim.pre): same grid
    // x geometry matrix, so an iso run with bodies has gravity + accretion + feedback.
    for ndim in 1u8..=3 {
        gen_body_source_iso(&out_dir, ndim, Coords::Cartesian);
    }
    gen_body_source_iso(&out_dir, 2, Coords::Cylindrical);
    gen_body_source_iso(&out_dir, 3, Coords::Cylindrical);
    gen_body_source_iso(&out_dir, 2, Coords::Spherical);
    gen_body_source_iso(&out_dir, 3, Coords::Spherical);
    for &cc in &[Coords::Cartesian, Coords::Cylindrical, Coords::Spherical] {
        gen_body_feedback_iso(&out_dir, 2, cc);
        gen_body_feedback_iso(&out_dir, 3, cc);
    }
    // RMHD (relativistic MHD): the KKC false-position c2p (100-step bracket), the
    // quartic-wave-speed HLLE flux, and the constrained-transport curl B-update.
    // the deepest substrate regime — iterative c2p + transcendental quartic + a
    // staggered offset stencil — all reaching build-time-compiled CPU + CUDA.
    gen_rmhd_c2p(&out_dir, 1, 100);
    gen_rmhd_c2p(&out_dir, 3, 100); // 3D for the production RmhdSubstrateKernelSet3D
    gen_rmhd_face_flux(&out_dir, 1);
    gen_rmhd_ct_curl(&out_dir);
    // 3D pieces for the production KernelSet3D: per-dir flux + edge EMF, the CT
    // single-kernels, the EOS-generic godunov/snapshot/rk2 (hydro D/S/tau).
    for dir in 0..3 {
        gen_rmhd_face_flux_3d(&out_dir, dir);
        gen_rmhd_edge_emf(&out_dir, dir, 3, ((dir + 1) % 3) as usize, ((dir + 2) % 3) as usize);
    }
    gen_rmhd_wave_speed_map(&out_dir, 3, Geom::cart(3));
    gen_rmhd_wave_speed_map(&out_dir, 3, Geom::sph(3));
    gen_rmhd_wave_speed_map(&out_dir, 3, Geom::cyl_3d());
    gen_rmhd_wave_speeds_cell(&out_dir, 3); // per-cell exact quartic -> wave_speed_l/r (geom-free)
    for dir in 0..3 {
        gen_rmhd_ct_curl_3d_dir(&out_dir, dir, Geom::cart(3));
        gen_rmhd_ct_curl_3d_dir(&out_dir, dir, Geom::sph(3));
        gen_rmhd_ct_curl_3d_dir(&out_dir, dir, Geom::cyl_3d());
    }
    gen_rmhd_bcell_from_bface(&out_dir, 3);
    gen_rmhd_bcell_godunov_euler(&out_dir, Geom::cart(3), 3);
    gen_rmhd_bcell_godunov_euler(&out_dir, Geom::sph(3), 3);
    gen_rmhd_bcell_godunov_euler(&out_dir, Geom::cyl_3d(), 3);
    gen_rmhd_bcell_godunov_rk2(&out_dir, Geom::cart(3), 3);
    gen_rmhd_bcell_godunov_rk2(&out_dir, Geom::sph(3), 3);
    gen_rmhd_bcell_godunov_rk2(&out_dir, Geom::cyl_3d(), 3);
    gen_rmhd_save_efield(&out_dir, 3);
    gen_rmhd_average_efield(&out_dir, 3);
    gen_rmhd_ghost_fill(&out_dir);
    // RMHD GAS update (D/S_k/tau) is EOS-generic — it uses the SAME unified runtime-coefficient
    // `_stage` kernel as hydro. only the constrained-transport BCELL predictor-corrector
    // (`rmhd_bcell_godunov_euler/rk2`, emitted above) + the post_godunov EMF time-average stay
    // baked + 2-stage, so the RMHD `godunov_stage` gates (a0,ac) -> {euler, rk2} on the bcell
    // step and rejects other coefficients (SSP-RK3 + CT is unimplemented).
    gen_godunov_stage(&out_dir, 3, "rmhd", true, Geom::cart(3), None);
    gen_godunov_stage(&out_dir, 3, "rmhd", true, Geom::sph(3), None);
    gen_godunov_stage(&out_dir, 3, "rmhd", true, Geom::cyl_3d(), None);
    // FUSED gas-stage + cell-B-predictor variants for all 3 geometries. one
    // launch per stage in the substrate's god_stage (vs the two-launch
    // baseline). algebra-validated: write sets disjoint (cons.* vs bc_*),
    // no inter-dependency, same 3D interior grade.
    for geom in [Geom::cart(3), Geom::sph(3), Geom::cyl_3d()] {
        gen_mhd_godunov_and_bcell(&out_dir, "rmhd", geom.clone(), "euler");
        gen_mhd_godunov_and_bcell(&out_dir, "rmhd", geom, "rk2");
    }
    gen_snapshot(&out_dir, 3, "rmhd", true, Geom::cart(3));
    // Isothermal MHD (Mignone 2007): the no-energy regime. c2p (rho, v_k only) + HLLE/HLLD
    // flux (D, S_k, B_k) + CFL map mirror NMHD; the CT stack is shared (Faraday induction is
    // regime-agnostic). gas stage carries no energy (has_energy=false).
    gen_imhd_c2p(&out_dir, 3);
    for dir in 0..3 {
        gen_imhd_face_flux_3d(&out_dir, dir);
        gen_imhd_hlld_face_flux(&out_dir, dir);
    }
    // iso CFL map + gas stage (no energy) for all 3 coords. the gas stage carries the ISOTHERMAL
    // geometric momentum source (cs^2*rho + 1/2|B|^2 pressure + inertial + lab-frame-B tension,
    // GeoSource::IsothermalMhd; Cartesian has zero source). the CT bcell predictor + edge-EMF /
    // curl / efield / ghost are regime-agnostic (reused from rmhd_*). snapshot/bcell/ghost are
    // geometry-independent (Cartesian emit covers all coords).
    for geom in [Geom::cart(3), Geom::sph(3), Geom::cyl_3d()] {
        gen_imhd_wave_speed_map(&out_dir, 3, geom.clone());
        gen_godunov_stage(&out_dir, 3, "imhd", false, geom, None);
    }
    gen_snapshot(&out_dir, 3, "imhd", false, Geom::cart(3));
    gen_imhd_bcell_from_bface(&out_dir, 3);
    gen_imhd_ghost_fill(&out_dir);
    // Newtonian MHD: the algebraic c2p + closed-form-magnetosonic HLLE flux + CFL map.
    // the constrained-transport stack (edge EMF / curl / bcell / efield / ghost) is
    // SHARED with RMHD (B evolution is regime-agnostic Faraday), so only these three
    // regime-specific physics kernels are emitted; the substrate reuses the rmhd_* CT.
    gen_nmhd_c2p(&out_dir, 3);
    for dir in 0..3 {
        gen_nmhd_face_flux_3d(&out_dir, dir);
        gen_nmhd_hllc_face_flux(&out_dir, dir);
        gen_nmhd_hlld_face_flux(&out_dir, dir);
    }
    gen_nmhd_wave_speed_map(&out_dir, 3, Geom::cart(3));
    gen_nmhd_wave_speed_map(&out_dir, 3, Geom::sph(3));
    gen_nmhd_wave_speed_map(&out_dir, 3, Geom::cyl_3d());
    // the NMHD gas stage carries the NEWTONIAN geometric momentum source (pressure +
    // inertial + magnetic tension via lab-frame B, GeoSource::NewtonianMhd) — the only
    // godunov piece that differs from RMHD by geometry. emitted for all 3 coords (Cartesian
    // has zero source, so it matches the EOS-generic stage). the fused god+bcell mirrors RMHD.
    for geom in [Geom::cart(3), Geom::sph(3), Geom::cyl_3d()] {
        gen_godunov_stage(&out_dir, 3, "nmhd", true, geom.clone(), None);
        gen_mhd_godunov_and_bcell(&out_dir, "nmhd", geom.clone(), "euler");
        gen_mhd_godunov_and_bcell(&out_dir, "nmhd", geom, "rk2");
    }
    // =========================================================================
    // 2.5D MHD (spatial D=2, vector DOF=3) constrained transport — docs/design/30.
    // cartesian. the out-of-plane Bz rides the ordinary induction-flux divergence
    // (no CT: with d/dz=0 only the in-plane field is div-B-constrained); only the
    // in-plane Bx,By use CT via the SINGLE corner E_z (edge dir=2 -> p1=x, p2=y).
    // fusion is disabled at D=2 (CPU unfused path), so no godunov_and_bcell_2d; the
    // RK2 efield save/average use the dimension-agnostic fused memcpy (no _2d copy
    // kernel needed on CPU). ncomp = 3 (B/momentum are 3-vectors) on the 2-axis grid.
    // =========================================================================
    {
        // gas/snapshot geom: cartesian, 2 grid axes, 3 vector components (DOF=3).
        let g2 = Geom::make(Coords::Cartesian, 3, vec![0, 1]);
        // shared regime-agnostic CT pieces: the corner E_z (edge dir=2), the in-plane
        // curl B-update (rmhd_ct_curl_2d already emitted above), the cell-B predictor
        // (euler/rk2, evolves all 3 components; Bz is final, Bx/By predictor), the
        // face->cell interpolation over the 2 in-plane components, and the ghosts.
        gen_rmhd_edge_emf(&out_dir, 2, 2, 0, 1);
        // device RK2 efield save/avg + the bcell^n snapshot copy on a 2D field need the 2d
        // index ABI (the 3d copy kernel OOBs on a 2d field — CUDA_ERROR_LAUNCH_FAILED).
        gen_rmhd_save_efield(&out_dir, 2);
        gen_rmhd_average_efield(&out_dir, 2);
        gen_rmhd_bcell_godunov_euler(&out_dir, g2.clone(), 2);
        gen_rmhd_bcell_godunov_rk2(&out_dir, g2.clone(), 2);
        gen_rmhd_bcell_from_bface(&out_dir, 2);
        gen_imhd_bcell_from_bface(&out_dir, 2);
        {
            let (k, w) = rmhd_ghost_fill_gv(2, 3);
            emit_gv(&out_dir, "rmhd_ghost_fill_2d", 2, &k, &w);
            let (k, w) = symbi_discretize::gv::imhd_ghost_fill_gv(2, 3);
            emit_gv(&out_dir, "imhd_ghost_fill_2d", 2, &k, &w);
            let (k, w) = symbi_discretize::scalar_ghost_fill_gv(2);
            emit_gv(&out_dir, "scalar_ghost_fill_2d", 2, &k, &w);
        }
        // RMHD regime physics (quartic HLLE flux + KKC c2p + exact-quartic CFL map +
        // the per-cell materialized wave speeds the HLLE flux reads).
        gen_rmhd_c2p(&out_dir, 2, 100);
        for dir in 0..2 {
            emit_rmhd_flux_gv(&out_dir, &format!("rmhd_face_flux_2d_{dir}"), 2, dir);
            // HLLC / HLLD 2.5D RMHD fluxes (cartesian, coord_n == dir) — parity with the 1D + 3D
            // emission so `--solver hllc|hlld` works on a 2D RMHD sim (e.g. rmhd_orszag_tang).
            gen_rmhd_hllc_face_flux(&out_dir, 2, dir);
            gen_rmhd_hlld_face_flux(&out_dir, 2, dir);
        }
        gen_rmhd_wave_speeds_cell(&out_dir, 2);
        gen_rmhd_wave_speed_map(&out_dir, 2, g2.clone());
        gen_godunov_stage(&out_dir, 2, "rmhd", true, g2.clone(), None);
        gen_snapshot(&out_dir, 2, "rmhd", true, g2.clone());
        // NMHD regime physics (algebraic c2p + closed-form magnetosonic HLLE/HLLC/HLLD).
        gen_nmhd_c2p(&out_dir, 2);
        for dir in 0..2 {
            let (k, w) = symbi_discretize::gv::nmhd_flux_gv(2, dir, dir as usize);
            emit_gv(&out_dir, &format!("nmhd_face_flux_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hllc_flux_gv(2, dir, dir as usize);
            emit_gv(&out_dir, &format!("nmhd_face_flux_hllc_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hlld_flux_gv(2, dir, dir as usize);
            emit_gv(&out_dir, &format!("nmhd_face_flux_hlld_2d_{dir}"), 2, &k, &w);
        }
        gen_nmhd_wave_speed_map(&out_dir, 2, g2.clone());
        gen_godunov_stage(&out_dir, 2, "nmhd", true, g2.clone(), None);
        gen_snapshot(&out_dir, 2, "nmhd", true, g2.clone());
        // IMHD regime physics (no-energy c2p + HLLE/HLLD flux).
        gen_imhd_c2p(&out_dir, 2);
        for dir in 0..2 {
            let (k, w) = symbi_discretize::gv::imhd_flux_gv(2, dir, dir as usize);
            emit_gv(&out_dir, &format!("imhd_face_flux_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::imhd_hlld_flux_gv(2, dir, dir as usize);
            emit_gv(&out_dir, &format!("imhd_face_flux_hlld_2d_{dir}"), 2, &k, &w);
        }
        gen_imhd_wave_speed_map(&out_dir, 2, g2.clone());
        gen_godunov_stage(&out_dir, 2, "imhd", false, g2.clone(), None);
        gen_snapshot(&out_dir, 2, "imhd", false, g2);
    }

    // =========================================================================
    // 2.5D CYLINDRICAL r-z AXISYMMETRIC MHD (docs/design/30): a 2-axis (r,z) grid carrying
    // a 3-component B/velocity — the swirl B_phi/v_phi is the out-of-plane DOF on the folded
    // phi symmetry. axes=[0,2]: grid axis 0=r (coord 0), grid axis 1=z (coord 2); phi (coord 1)
    // is out of plane. the SINGLE CT edge is E_phi (name_k=1); the in-plane curl carries the
    // cylindrical metric -(1/r) d_r(r E_phi) on the z-face (dir=1), flat on the r-face (dir=0).
    // ONLY the geometry-dependent kernels are emitted here — c2p / snapshot / ghost /
    // bcell_from_bface / save+avg-efield / wave_speeds_cell are geometry-FREE and REUSED from
    // the cartesian 2.5D block above (DOF=3 already, same field shapes). all three regimes.
    // =========================================================================
    {
        let cyl = Geom::cyl_rz(); // Cylindrical, ncomp=3, axes=[0,2] -> suffix "_cyl_rz"
        // shared regime-agnostic CT: the corner E_phi (name_k=1, grid offset axes 0,1) + the
        // metric in-plane curl + the cell-B flux predictor (area-weighted divergence, axes=[0,2]).
        gen_rmhd_edge_emf(&out_dir, 1, 2, 0, 1);
        for dir in 0..2 {
            gen_rmhd_ct_curl_cyl_rz(&out_dir, dir, &cyl);
        }
        gen_rmhd_bcell_godunov_euler(&out_dir, cyl.clone(), 2);
        gen_rmhd_bcell_godunov_rk2(&out_dir, cyl.clone(), 2);
        // RMHD regime physics: HLLE quartic flux (normal coord_n = axes[dir]) + CFL map +
        // gas godunov (cyl geo source). c2p / wave_speeds_cell / snapshot reused from above.
        gen_rmhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "rmhd", true, cyl.clone(), None);
        for dir in 0u8..2 {
            let cn = cyl.axes[dir as usize];
            let (k, w) = symbi_discretize::gv::rmhd_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("rmhd_face_flux_cyl_rz_2d_{dir}"), 2, &k, &w);
            // HLLC / HLLD parity (normal coord_n = axes[dir]) so `--solver hllc|hlld` works on a
            // cyl r-z RMHD sim (r-phi reuses the cartesian flux via the "" suffix; cart done above).
            let (k, w) = symbi_discretize::gv::rmhd_hllc_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("rmhd_face_flux_cyl_rz_hllc_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::rmhd_hlld_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("rmhd_face_flux_cyl_rz_hlld_2d_{dir}"), 2, &k, &w);
        }
        // NMHD regime physics (algebraic c2p + closed-form magnetosonic HLLE/HLLC/HLLD).
        gen_nmhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "nmhd", true, cyl.clone(), None);
        for dir in 0u8..2 {
            let cn = cyl.axes[dir as usize];
            let (k, w) = symbi_discretize::gv::nmhd_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("nmhd_face_flux_cyl_rz_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hllc_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("nmhd_face_flux_cyl_rz_hllc_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hlld_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("nmhd_face_flux_cyl_rz_hlld_2d_{dir}"), 2, &k, &w);
        }
        // IMHD regime physics (no-energy c2p + HLLE/HLLD flux).
        gen_imhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "imhd", false, cyl.clone(), None);
        for dir in 0u8..2 {
            let cn = cyl.axes[dir as usize];
            let (k, w) = symbi_discretize::gv::imhd_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("imhd_face_flux_cyl_rz_2d_{dir}"), 2, &k, &w);
            let (k, w) = symbi_discretize::gv::imhd_hlld_flux_gv(2, dir, cn);
            emit_gv(&out_dir, &format!("imhd_face_flux_cyl_rz_hlld_2d_{dir}"), 2, &k, &w);
        }
    }

    // =========================================================================
    // 2.5D CYLINDRICAL r-phi DISK MHD (docs/design/30): a 2-axis (r,phi) grid carrying a
    // 3-component B/velocity — the VERTICAL B_z/v_z is the out-of-plane DOF. axes=[0,1]: grid
    // axis 0=r (coord 0), grid axis 1=phi (coord 1); z (coord 2) is out of plane. the SINGLE CT
    // edge is E_z (name_k=2); the in-plane curl carries the cylindrical metric -(1/r) d_phi E_z
    // on the r-face (dir=0), flat on the phi-face (dir=1) — the MIRROR of r-z. the out-of-plane
    // B_z flux-evolves through the area-weighted cyl divergence (which IS the correct z-curl here,
    // unlike r-z's B_phi). the FLUX + edge-EMF are REUSED from the cartesian 2.5D block (axes [0,1]
    // = identity, so coord_n == dir and the E_z corner is bit-identical); only the metric curl,
    // wave-speed map, gas godunov (cyl geo source), and bcell predictor are geometry-dependent.
    // all three regimes.
    // =========================================================================
    {
        let cyl = Geom::cyl_rphi_mhd(); // Cylindrical, ncomp=3, axes=[0,1] -> suffix "_cyl_rphi"
        // CT: corner E_z (rmhd_edge_emf_2d_2) REUSED from the cartesian block. metric in-plane
        // curl (dir=0 B_r: (1/r)d_phi; dir=1 B_phi: flat) + the cell-B flux predictor (area-
        // weighted divergence over axes=[0,1] — correct for the out-of-plane B_z).
        for dir in 0..2 {
            gen_rmhd_ct_curl_cyl_rphi(&out_dir, dir, &cyl);
        }
        gen_rmhd_bcell_godunov_euler(&out_dir, cyl.clone(), 2);
        gen_rmhd_bcell_godunov_rk2(&out_dir, cyl.clone(), 2);
        // the FLUX is REUSED from cartesian (axes [0,1] = identity -> coord_n == dir -> bit-
        // identical; mhd_flux_suffix returns "" for r-phi). c2p / wave_speeds_cell / snapshot /
        // ghost / bcell_from_bface / save+avg-efield also reused. only wave-speed + gas godunov
        // (the cyl metric: CFL phi-width = r*dphi, centrifugal/hoop source) are emitted here.
        gen_rmhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "rmhd", true, cyl.clone(), None);
        gen_nmhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "nmhd", true, cyl.clone(), None);
        gen_imhd_wave_speed_map(&out_dir, 2, cyl.clone());
        gen_godunov_stage(&out_dir, 2, "imhd", false, cyl.clone(), None);
    }

    // =========================================================================
    // 1.5D MHD (spatial D=1, vector DOF=3) — docs/design/30. NO constrained transport:
    // C(1,2)=0 edges (the StaggerComplex empty case), so no edge_emf / ct_curl. the
    // in-plane Bx (c=0) is carried on its (thin) face but never curled -> it stays at its
    // constant IC (the "Bx is a parameter" rule, realized as the no-edge case). By,Bz
    // (c>=1, out-of-plane) ride the ordinary induction-flux divergence (bcell_godunov).
    // bcell_from_bface_1d interpolates the const Bx + the 1-component energy correction.
    // ncomp = 3 on the 1-axis grid. (rmhd_c2p_1d is already emitted above.)
    // =========================================================================
    {
        let g1 = Geom::make(Coords::Cartesian, 3, vec![0]);
        // the device bcell^n snapshot copy on a 1D field needs the 1d save kernel (no efield
        // save/avg in 1.5D — 0 edges — but the snapshot path still copies bcell on device).
        gen_rmhd_save_efield(&out_dir, 1);
        gen_rmhd_bcell_godunov_euler(&out_dir, g1.clone(), 1);
        gen_rmhd_bcell_godunov_rk2(&out_dir, g1.clone(), 1);
        gen_rmhd_bcell_from_bface(&out_dir, 1);
        gen_imhd_bcell_from_bface(&out_dir, 1);
        {
            let (k, w) = rmhd_ghost_fill_gv(1, 3);
            emit_gv(&out_dir, "rmhd_ghost_fill_1d", 1, &k, &w);
            let (k, w) = symbi_discretize::gv::imhd_ghost_fill_gv(1, 3);
            emit_gv(&out_dir, "imhd_ghost_fill_1d", 1, &k, &w);
            let (k, w) = symbi_discretize::scalar_ghost_fill_gv(1);
            emit_gv(&out_dir, "scalar_ghost_fill_1d", 1, &k, &w);
        }
        // RMHD regime physics (c2p already emitted; HLLE flux reads the materialized speeds).
        emit_rmhd_flux_gv(&out_dir, "rmhd_face_flux_1d_0", 1, 0);
        gen_rmhd_wave_speeds_cell(&out_dir, 1);
        gen_rmhd_wave_speed_map(&out_dir, 1, g1.clone());
        gen_godunov_stage(&out_dir, 1, "rmhd", true, g1.clone(), None);
        gen_snapshot(&out_dir, 1, "rmhd", true, g1.clone());
        // NMHD regime physics.
        gen_nmhd_c2p(&out_dir, 1);
        {
            let (k, w) = symbi_discretize::gv::nmhd_flux_gv(1, 0, 0);
            emit_gv(&out_dir, "nmhd_face_flux_1d_0", 1, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hllc_flux_gv(1, 0, 0);
            emit_gv(&out_dir, "nmhd_face_flux_hllc_1d_0", 1, &k, &w);
            let (k, w) = symbi_discretize::gv::nmhd_hlld_flux_gv(1, 0, 0);
            emit_gv(&out_dir, "nmhd_face_flux_hlld_1d_0", 1, &k, &w);
        }
        gen_nmhd_wave_speed_map(&out_dir, 1, g1.clone());
        gen_godunov_stage(&out_dir, 1, "nmhd", true, g1.clone(), None);
        gen_snapshot(&out_dir, 1, "nmhd", true, g1.clone());
        // IMHD regime physics.
        gen_imhd_c2p(&out_dir, 1);
        {
            let (k, w) = symbi_discretize::gv::imhd_flux_gv(1, 0, 0);
            emit_gv(&out_dir, "imhd_face_flux_1d_0", 1, &k, &w);
            let (k, w) = symbi_discretize::gv::imhd_hlld_flux_gv(1, 0, 0);
            emit_gv(&out_dir, "imhd_face_flux_hlld_1d_0", 1, &k, &w);
        }
        gen_imhd_wave_speed_map(&out_dir, 1, g1.clone());
        gen_godunov_stage(&out_dir, 1, "imhd", false, g1.clone(), None);
        gen_snapshot(&out_dir, 1, "imhd", false, g1);
    }

    // emit the single registry from everything generated above — replaces the
    // hand-maintained include!/const lines in lib.rs (docs/design/15 §3).
    write_registry(&out_dir);
    // STALENESS FIX: the emitted kernels are a pure function of the SUBSTRATE physics
    // (symbi-hydro carrier fns + symbi-discretize gv builders + symbi-ir emitter), none
    // of which live in THIS package. a build script with NO `rerun-if` directive reruns
    // only when this package's OWN files change (Cargo book) — NOT when a build-DEPENDENCY
    // recompiles, contrary to the prior comment here. that left the generated CPU+CUDA
    // kernels stale after any gv-builder / physics edit (GPU-vs-CPU mismatch / gpu=0 until
    // a manual `cargo clean -p symbi-aot`). watch the substrate source explicitly so any
    // physics change regenerates the kernels. NOTE: emitting any rerun-if-changed disables
    // the default whole-package watch, so build.rs is listed too.
    println!("cargo:rerun-if-changed=build.rs");
    // Gate 3 GPU smem tiling opt-in (docs/design/22). same A/B-honesty reason.
    println!("cargo:rerun-if-env-changed=SYMBI_GPU_SMEM");
    // part-1 loop-lowering: bounds-check-free field access (the ~8x spike win).
    println!("cargo:rerun-if-env-changed=SYMBI_UNCHECKED_LOADS");
    // debug-emit-knobs gates the three a/b env knobs; only track them for rebuild when the feature is on. off (default) = these envs are never read, so no need to invalidate on change.
    if std::env::var_os("CARGO_FEATURE_DEBUG_EMIT_KNOBS").is_some() {
        println!("cargo:rerun-if-env-changed=SYMBI_TILE_CPU");
        println!("cargo:rerun-if-env-changed=SYMBI_VEC_LOOP");
        println!("cargo:rerun-if-env-changed=SYMBI_GEN_SERIAL");
    }
    for dep_src in [
        "../symbi-ir/src",
        "../symbi-discretize/src",
        "../symbi-hydro/src",
        "../symbi-geometry/src",
        "../symbi-grid/src",
        "../symbi-algebra/src",
    ] {
        println!("cargo:rerun-if-changed={dep_src}");
    }
}
