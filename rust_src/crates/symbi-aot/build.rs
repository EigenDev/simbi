/// one row in the regime bake table — the kernel-name prefix + whether the
/// regime carries an energy conservation law. iso (mass + mom only) sets
/// `has_energy = false`; adiabatic / SRHD / RMHD set `true`.
struct RegimeBuild {
    prefix:     &'static str,
    has_energy: bool,
}

/// every regime we AOT-bake fused-source kernels for. SRHD + RMHD slot in
/// as additional rows once their fused-source path validates on the GPU.
const REGIMES: &[RegimeBuild] = &[
    RegimeBuild { prefix: "iso",       has_energy: false },
    RegimeBuild { prefix: "adiabatic", has_energy: true  },
];

/// build-time identity of a fused-source family — one variant per AOT slug.
/// mirrors the runtime `symbi_hydro::FusedSourceFamily` but carries NO
/// runtime params: `source_specs(d, has_energy)` materializes the spec list
/// build.rs needs from the symbi-hydro factory functions, parameterized by
/// ndim + the regime's energy flag.
#[derive(Clone, Copy)]
enum FamilyKind {
    UniformAccel,
    PointMassGrav,
}

impl FamilyKind {
    fn slug(self) -> &'static str {
        match self {
            Self::UniformAccel  => "uniform_accel",
            Self::PointMassGrav => "point_mass_grav",
        }
    }

    fn source_specs(self, d: usize, has_energy: bool) -> Vec<symbi_hydro::source_spec::SourceSpec> {
        match self {
            Self::UniformAccel => {
                symbi_hydro::source_spec::uniform_acceleration_sources(d, has_energy)
            }
            Self::PointMassGrav => {
                symbi_hydro::source_spec::point_mass_gravity_sources(d, has_energy)
            }
        }
    }
}

