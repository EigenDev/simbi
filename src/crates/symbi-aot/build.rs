fn write_kernel(out_dir: &str, file: &str, desc: &symbi_ir::emit::KernelDescriptor) {
    let buffers: Vec<(String, bool)> = desc
        .field_bindings
        .iter()
        .map(|b| (b.field.name(), b.is_output))
        .collect();
    // the signature order is recorded in the generated file's header so callers
    // (and a human) can match the positional kernel signature.
    let mut src = String::new();
    src.push_str("// generated by build.rs from a substrate RegimeSpec — do not edit.\n");
    src.push_str(&format!("// buffers (in signature order): {:?}\n", buffers));
    src.push_str(&format!(
        "// scalars (in signature order): {:?}\n",
        desc.param_names
    ));
    src.push_str(&desc.source);
    fs::write(Path::new(out_dir).join(file), src).expect("failed to write generated kernel");
}

// emit from one IR graph: the CPU Rust (compiled into the crate) AND the
// backend-neutral lowered IR — `prepare` (scalarize + buffer-bind, no renderer)
// serialized to `{kernel_name}.ir.json` and exposed as a const, rendered to any
// backend at runtime via `render_from_ir`. one physics graph,
// one neutral artifact. `prepare` runs twice (once inside emit_kernel_cpu, once
// here) — deterministic, build-time only.
//
// the CPU file name is DERIVED from kernel_name (`{kernel_name}_generated.rs`), which
// is unique per (regime, ndim, dir), so the SAME regime can be instantiated at
// multiple ndims without colliding on a fixed filename (D-generic ports).
// serial-twin generation is ON by default (the universal cover executor's per-block
// kernel). opt out with SYMBI_GEN_SERIAL=0/off/false/no for a ~1.5x-leaner build.
fn serial_twins_enabled() -> bool {
    // debug-emit-knobs gates the SYMBI_GEN_SERIAL read (build scripts read CARGO_FEATURE_* env vars; cfg! does not reflect feature flags inside a build script); feature off (default) = canonical env-unset shape (true, serial twins on).
    if std::env::var_os("CARGO_FEATURE_DEBUG_EMIT_KNOBS").is_none() {
        return true;
    }
    match std::env::var("SYMBI_GEN_SERIAL") {
        Ok(s) => !matches!(
            s.trim().to_ascii_lowercase().as_str(),
            "0" | "off" | "false" | "no"
        ),
        Err(_) => true,
    }
}

// the artifact-producing emit: CPU source + the serialized neutral IR blob.
// `output_support` is the GvKernel's declared output support,
// stamped onto the Prepared AFTER prepare — no renderer reads it, so
// it does not ride KernelEmitInputs. the serial twin reuses the same blob, so
// the declaration travels with both registrations.
fn write_both_with_support(
    out_dir: &str,
    graph: &Graph,
    inputs: &KernelEmitInputs,
    output_support: Option<&symbi_ir::Support>,
) {
    let cpu_file = format!("{}_generated.rs", inputs.kernel_name);
    write_kernel(out_dir, &cpu_file, &emit_kernel_cpu(graph, inputs));
    let mut prepared = prepare(graph, inputs);
    prepared.output_support = output_support.cloned();
    let ir = prepared_to_ir(&prepared);
    fs::write(
        Path::new(out_dir).join(format!("{}.ir.json", inputs.kernel_name)),
        &ir,
    )
    .expect("failed to write neutral ir blob");
    REGISTRY
        .lock()
        .unwrap()
        .push((cpu_file, inputs.kernel_name.to_string()));

    // emit a `{name}_serial` twin (no internal rayon) so the cover executor can
    // dispatch a disjoint block cover in ONE fork-join — the universal scheduling
    // path. ON by default (the +13% auto-block win is the standard behavior); opt
    // out with SYMBI_GEN_SERIAL=0/off/false for a leaner/faster build (the executor
    // then falls back to the parallel kernel — same results, no auto-blocking).
    if serial_twins_enabled() {
        let serial_name = format!("{}_serial", inputs.kernel_name);
        let serial_inputs = KernelEmitInputs {
            kernel_name: &serial_name,
            ndim: inputs.ndim,
            target: inputs.target.clone(),
            // the serial twin is the SAME kernel, parallel-stripped — same buffer topology.
            coalesce_layout: inputs.coalesce_layout,
            field_inputs: inputs.field_inputs,
            scalar_params: inputs.scalar_params,
            field_writes: inputs.field_writes,
            coord_components: inputs.coord_components,
            device_preamble: inputs.device_preamble,
            tile_spec: inputs.tile_spec,
        };
        let serial_file = format!("{serial_name}_generated.rs");
        write_kernel(
            out_dir,
            &serial_file,
            &emit_kernel_cpu_serial(graph, &serial_inputs),
        );
        // the neutral IR blob is renderer-agnostic (same graph) — reuse it under
        // the serial name so the registry stays uniform (CPU-only path; unused).
        fs::write(
            Path::new(out_dir).join(format!("{serial_name}.ir.json")),
            &ir,
        )
        .expect("failed to write serial ir blob");
        REGISTRY.lock().unwrap().push((serial_file, serial_name));
    }
}

// write the single registry module from everything write_both emitted this run:
// one `include!` per CPU kernel + one `<KERNEL>_IR` blob const per kernel (the
// serialized backend-neutral lowered IR / Prepared). the const
// name + .ir.json filename derive uniformly from kernel_name (iso_c2p_1d ->
// ISO_C2P_1D_IR + iso_c2p_1d.ir.json), so no per-kernel hand-registration survives.
fn write_registry(out_dir: &str) {
    let reg = REGISTRY.lock().unwrap();
    let mut src = String::new();
    src.push_str("// generated by build.rs — the kernel registry.\n");
    src.push_str(
        "// one include! per CPU kernel + one neutral IR blob const per kernel. do not edit.\n",
    );
    for (cpu_file, kernel_name) in reg.iter() {
        src.push_str(&format!(
            "include!(concat!(env!(\"OUT_DIR\"), \"/{cpu_file}\"));\n"
        ));
        src.push_str(&format!(
            "pub const {}_IR: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/{kernel_name}.ir.json\"));\n",
            kernel_name.to_uppercase(),
        ));
    }
    // the name -> (structured CPU fn, neutral IR blob) lookup:
    // the D-generic SubstrateKernelSet<.., const D> builds a kernel name from
    // (regime, ndim, dir) and resolves the instance HERE — no hand-maintained
    // `match (D, dir)` per regime. `KernelFn<S>` (lib.rs) is the structured ABI fn
    // pointer; the generic fn item `k::<S>` coerces to it. one entry per kernel,
    // auto-registered from everything emitted this run.
    src.push_str(
        "\n/// resolve a generated kernel by name to its structured CPU fn + neutral IR blob.\n",
    );
    src.push_str("pub fn kernel_by_name<S: Scalar + OrderedNumeric>(name: &str) -> Option<(KernelFn<S>, &'static str)> {\n");
    src.push_str("    Some(match name {\n");
    for (_cpu_file, kernel_name) in reg.iter() {
        src.push_str(&format!(
            "        \"{kernel_name}\" => ({kernel_name}::<S>, {}_IR),\n",
            kernel_name.to_uppercase(),
        ));
    }
    src.push_str("        _ => return None,\n    })\n}\n");
    // the ENUMERABLE registry: every generated kernel's (name, neutral IR blob).
    // registry-wide audits (the ghost-width law over FieldLoadAt stencil reach)
    // iterate this list, so a newly generated kernel is audited the build it appears in,
    // without being named by hand.
    src.push_str(
        "\n/// every generated kernel's (name, neutral IR blob), in registration order.\n",
    );
    src.push_str("pub static IR_BLOBS: &[(&str, &str)] = &[\n");
    for (_cpu_file, kernel_name) in reg.iter() {
        src.push_str(&format!(
            "    (\"{kernel_name}\", {}_IR),\n",
            kernel_name.to_uppercase(),
        ));
    }
    src.push_str("];\n");
    fs::write(Path::new(out_dir).join("kernels_registry.rs"), src)
        .expect("failed to write kernel registry");
}

